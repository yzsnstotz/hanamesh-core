export const marketLocaleNames = {
  zh: '简体中文',
  en: 'English',
  ja: '日本語',
  'pt-BR': 'Português (Brasil)',
  es: 'Español',
  ko: '한국어',
  vi: 'Tiếng Việt',
  id: 'Bahasa Indonesia',
  ru: 'Русский',
};

export function marketContentLocale(value) {
  const primary = (value ?? '').toLowerCase().split('-')[0];
  if (primary === 'pt') return 'pt-BR';
  return Object.hasOwn(marketLocaleNames,primary) ? primary : 'en';
}

export function marketLocalizedSelection(value, locale, original) {
  if (typeof value === 'string') return {text:value,locale:null};
  const translations = value?.byLocale ?? value;
  const requested = marketContentLocale(locale);
  if (typeof translations?.[requested] === 'string') return {text:translations[requested],locale:requested};
  if (typeof translations?.en === 'string') return {text:translations.en,locale:'en'};
  return original ?? {text:'',locale:null};
}

export function marketCapabilitySelection(item, locale) {
  const summary = item.summary;
  let original;
  if (typeof summary?.en === 'string') original = {text:summary.en,locale:'en'};
  else if (typeof summary?.zh === 'string') original = {text:summary.zh,locale:'zh'};
  else if (typeof summary === 'string') original = {text:summary,locale:null};
  return marketLocalizedSelection(item.overview?.does, locale, original);
}
